-- Stoke Yange — Supabase schema (run in SQL editor after creating a project)
-- Offline-first: IndexedDB is source of truth on device; this is the cloud mirror.

create extension if not exists "pgcrypto";

-- Profiles linked to auth.users
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  shop_name text default 'Iduka Ryanjye',
  email text,
  created_at timestamptz default now()
);

-- Shop data scoped by user_id
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  local_id bigint,
  name text not null,
  category text not null,
  unit text not null,
  cost numeric not null default 0,
  price numeric not null default 0,
  stock numeric not null default 0,
  min numeric not null default 0,
  emoji text default '📦',
  updated_at timestamptz default now(),
  unique (user_id, local_id)
);

create table if not exists public.parties (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  local_id bigint,
  name text not null,
  phone text default '',
  kind text not null check (kind in ('customer', 'supplier')),
  created_at timestamptz default now(),
  unique (user_id, local_id)
);

create table if not exists public.sales (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  local_id bigint,
  product_local_id bigint,
  product_name text not null,
  qty numeric not null,
  unit_price numeric not null,
  unit_cost numeric not null,
  total numeric not null,
  type text not null check (type in ('cash', 'credit')),
  party_local_id bigint,
  created_at timestamptz not null,
  reversed smallint default 0,
  unique (user_id, local_id)
);

create table if not exists public.debts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  local_id bigint,
  party_local_id bigint not null,
  description text not null,
  amount numeric not null,
  created_at timestamptz not null,
  sale_local_id bigint,
  unique (user_id, local_id)
);

create table if not exists public.payments (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  local_id bigint,
  party_local_id bigint not null,
  amount numeric not null,
  created_at timestamptz not null,
  unique (user_id, local_id)
);

create table if not exists public.movements (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  local_id bigint,
  product_local_id bigint not null,
  type text not null,
  qty numeric not null,
  unit_cost numeric,
  created_at timestamptz not null,
  unique (user_id, local_id)
);

-- RLS
alter table public.profiles enable row level security;
alter table public.products enable row level security;
alter table public.parties enable row level security;
alter table public.sales enable row level security;
alter table public.debts enable row level security;
alter table public.payments enable row level security;
alter table public.movements enable row level security;

create policy "own profile" on public.profiles for all using (auth.uid() = id) with check (auth.uid() = id);
create policy "own products" on public.products for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "own parties" on public.parties for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "own sales" on public.sales for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "own debts" on public.debts for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "own payments" on public.payments for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "own movements" on public.movements for all using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- Auto profile on signup
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, email) values (new.id, new.email);
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();
